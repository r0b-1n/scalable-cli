// Translate a raw API enum code through a label map; unknown codes fall back
// to prettified text (FOO_BAR → "Foo bar") so new backend values never break.
/**
 * `ASSET_CLASS` → "Asset class". The last-resort rendering for an enum value
 * the CLI returned that no dictionary covers — a new backend code should still
 * read as words rather than as a shouting constant.
 *
 * Call this directly ONLY for genuinely open-ended enum values. It is not a
 * translation: anything you can name at build time belongs in a dictionary
 * below, or it will stay English in every locale.
 */
export function prettifyEnum(raw: unknown): string {
  const pretty = String(raw).replace(/_/g, " ").toLowerCase();
  return pretty.charAt(0).toUpperCase() + pretty.slice(1);
}

/** Looks `raw` up in a locale dictionary, falling back to `prettifyEnum`. */
export function enumLabel(
  map: Record<string, string>,
  raw: unknown,
  fallback = "—"
): string {
  if (raw == null || raw === "") return fallback;
  const hit = map[String(raw).toUpperCase()];
  return hit ?? prettifyEnum(raw);
}
